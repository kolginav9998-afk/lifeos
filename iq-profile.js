export const MIN_PER_SCALE = 3;

// answers: { id: 1…5 | null }. Среднее по шкале после переворота обратных утверждений; если ответов на шкалу меньше трёх, значение null.
export function scoreProfile(answers) {
  const out = { n: 0 };
  for (const s of SCALES) {
    const vals = ITEMS.filter(i => i.scale === s.key).map(i => { const v = answers[i.id]; return Number.isInteger(v) && v >= 1 && v <= 5 ? (i.rev ? 6 - v : v) : null; }).filter(v => v !== null);
    out.n += vals.length;
    out[s.key] = vals.length >= MIN_PER_SCALE ? Math.round((vals.reduce((a, b) => a + b, 0) / vals.length) * 100) / 100 : null;
  }
  return out;
}
