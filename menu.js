export const menuItems = (sections = MENU_SECTIONS) => sections.flatMap(s => s.items.map(i => ({ ...i, section: s.title })));

const norm = s => String(s ?? '').toLowerCase().replace(/ё/g, 'е');
const wordsOf = s => norm(s).split(/[^a-zа-я0-9]+/).filter(Boolean);
// «Основа» слова: отбрасываем окончание, чтобы «зарплату» находило «зарплата», «стирал» — «стирка».
const stem = w => (w.length > 5 ? w.slice(0, w.length - 2) : w.length > 3 ? w.slice(0, w.length - 1) : w);
const sameStem = (a, b) => {
  if (a === b) return true;
  const [s, l] = a.length <= b.length ? [a, b] : [b, a];
  return (s.length >= 4 && l.startsWith(s)) || (stem(a).length >= 4 && stem(a) === stem(b));        // короткие слова («с», «в», «на») не считаются началом других слов
};

// Поиск по каталогу: каждое слово запроса должно найтись в названии, подсказке или ключевых словах раздела.
// Название весит больше ключевых слов, ключевые слова больше подсказки. Возвращает разделы по убыванию совпадения.
export function searchMenu(query, sections = MENU_SECTIONS, limit = 12) {
  const qs = wordsOf(query).filter(w => w.length >= 2);
  if (!qs.length) return [];
  const out = [];
  menuItems(sections).forEach((item, order) => {
    const fields = [[5, wordsOf(item.title)], [3, item.words.flatMap(wordsOf)], [1, wordsOf(item.hint)]];
    let score = 0;
    for (const q of qs) {
      const w = Math.max(0, ...fields.map(([weight, ws]) => (ws.some(x => sameStem(q, x) || sameStem(stem(q), stem(x))) ? weight : 0)));
      if (!w) return;
      score += w;
    }
    out.push({ item, score, order });
  });
  out.sort((a, b) => b.score - a.score || a.order - b.order);
  return out.slice(0, limit).map(x => x.item);
}
