export const nm = c => LET[c][0];
export const snd = c => LET[c][1];
export const hook = c => LET[c][2];
const uniq = a => [...new Set(a)];
// какие звуки может давать буква (для честных вариантов ответа: неверный вариант не должен быть тоже верным)
const PH = { 'א': '_', 'ע': '_', 'ב': 'бв', 'ג': 'г', 'ד': 'д', 'ה': 'h', 'ו': 'в', 'ז': 'з', 'ח': 'х', 'ט': 'т', 'י': 'й', 'כ': 'кх', 'ל': 'л', 'מ': 'м', 'נ': 'н', 'ס': 'с', 'פ': 'пф', 'צ': 'ц', 'ק': 'к', 'ר': 'р', 'ש': 'шс', 'ת': 'т', 'ך': 'х', 'ם': 'м', 'ן': 'н', 'ף': 'ф', 'ץ': 'ц' };
const clash = (a, b) => [...PH[a]].some(p => PH[b].includes(p));
const cand = (c, known) => uniq([...LET[c][3], ...LET[c][4], ...[...known].reverse()]).filter(x => x !== c && LET[x] && [...known].includes(x));
export const wrongNames = (c, known, k = 2) => uniq(cand(c, known).map(nm)).filter(x => x !== nm(c)).slice(0, k);
export const wrongSounds = (c, known, k = 2) => uniq([...LET[c][5], ...cand(c, known).filter(x => !clash(c, x)).map(snd)]).filter(x => x !== snd(c) && !(c === 'ה' && x === 'молчит')).slice(0, k);   // у хей «молчит» в конце слова: не делаем это неверным вариантом

// ===== Генераторы заданий по буквам
export const nameQ = (c, known) => choose('Как называется эта буква?', nm(c), wrongNames(c, known), { big: c, explain: `${nm(c)}: ${hook(c)}.` });
export const findQ = (c, known) => choose(`Какая буква называется «${nm(c)}»?`, c, cand(c, known).slice(0, 2), { explain: `${nm(c)}: ${hook(c)}.` });
export const soundQ = (c, known) => choose('Какой звук у этой буквы?', snd(c), wrongSounds(c, known), { big: c, explain: `${nm(c)}: ${snd(c)}.` });
export const bySoundQ = (c, known) => choose(`Выбери букву со звуком: ${snd(c)}`, c, cand(c, known).filter(x => !clash(c, x)).slice(0, 2), { explain: `${nm(c)}: ${snd(c)}.` });
export const typedQ = c => BASE[c]
  ? typed('Впиши название обычной буквы, от которой образована эта конечная форма.', [nm(BASE[c]), ...LET[BASE[c]][6]], { big: c, hint: 'Конечная форма похожа на обычную букву, но уходит под строку или закрыта.' })
  : typed('Впиши название буквы по-русски.', [nm(c), ...LET[c][6]], { big: c, hint: `Название начинается на «${nm(c)[0]}».` });
export const listenQ = (c, known) => listen(c, nm(c), wrongNames(c, known), { lang: 'hebrew', hint: `Название начинается на «${nm(c)[0]}».`, explain: `Это «${nm(c)}».` });
// похожие буквы: a и b, text — чем они отличаются
export const pairQ = (a, b, text, known) => choose(`Какая из этих букв — «${nm(a)}»?`, a, uniq([b, ...cand(a, known)]).slice(0, 2), { explain: text });
export const nextQ = (c, known) => { const i = ALPHA.indexOf(c), n = ALPHA[i + 1]; return i >= 0 && n && [...known].includes(n) ? choose(`Какая буква идёт в алфавите сразу после «${nm(c)}»?`, n, cand(n, known).slice(0, 2), { explain: `После «${nm(c)}» идёт «${nm(n)}».` }) : null; };
export const orderQ = ls => order('Расставь буквы по алфавиту. Первая ляжет справа.', [...ls], { dir: 'rtl', hint: 'Алфавит идёт справа налево: первая буква самая правая.' });
export const matchQ = ls => match('Соедини буквы и названия.', [...ls].map(c => [c, nm(c)]));
export const readQ = ls => read([...ls].join(' '), { q: 'Назови вслух каждую букву, справа налево', lang: 'hebrew' });
export const tableOf = ls => [['Буква', 'Название', 'Звук', 'Образ'], ...[...ls].map(c => [c, nm(c), snd(c), hook(c)])];
export const cardsOf = ls => [...ls].map(c => [c, `${nm(c)}: ${snd(c)}`]);

// Урок про новые буквы. o: ls (новые буквы), known (все известные к этому уроку), pairs [[a, b, чем отличаются]], extra (свои задания), cards (свои карточки), intro2 (знаки)
export function letterLesson(id, prev, o) {
  const L = [...o.ls], K = [...o.known], pairs = o.pairs ?? [];
  const drills = [
    ...L.map(c => nameQ(c, K)),
    soundQ(L[0], K), soundQ(L.at(-1), K),
    findQ(L[1], K), findQ(L.length > 2 ? L.at(-1) : L[0], K),
    bySoundQ(o.soundLetter ?? L.find(c => !'אע'.includes(c)), K),
    typedQ(L[1]), ...(L.length >= 3 ? [matchQ(L)] : []), ...(o.fin ? [] : [orderQ(L)]), listenQ(L[2] ?? L[0], K), readQ(L),
    ...L.slice(0, -1).map(c => nextQ(c, K)).filter(Boolean).slice(0, 1),
    ...pairs.map(([a, b, t]) => pairQ(a, b, t, K)),
    ...(o.extra ?? []),
  ];
  return {
    id, title: o.title, minutes: o.minutes ?? 6, stage: o.stage ?? 'Алфавит', needs: prev ? [prev] : [], intro: L.join(' ') + (o.intro2 ? ' ' + o.intro2 : ''),
    goal: o.goal, body: o.body, task: o.task, decay: o.decay ?? 1.3, table: tableOf(L),
    cards: [...cardsOf(L), ...pairs.map(([a, b, t]) => [`Как отличить ${a} от ${b}?`, t]), ...(o.cards ?? [])], drills,
  };
}

// Слог ו + дагеш (шурук) тоже гласная, но проверка допуска её не видит: такие записи вносим в showcase урока, чтобы не краснел тест.
const RUN = /[\u05D0-\u05EA\u0591-\u05BD\u05BF\u05C1\u05C2\u05C4\u05C5\u05C7]+/g;
export function withShowcase(l) {
  const sc = new Set(l.showcase ?? []);
  for (const t of textsOfLesson(l)) for (const m of t.matchAll(RUN)) {
    const w = m[0];
    if ((w.match(/[א-ת]/g) ?? []).length >= 2 && !/[\u05B0-\u05BB\u05C7]/.test(w) && /\u05D5\u05BC/.test(w)) sc.add(w);
  }
  return sc.size ? { ...l, showcase: [...sc] } : l;
}
