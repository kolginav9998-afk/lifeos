// Урок про новые огласовки. o: newMarks, known (все изученные знаки гласных), cons, pairs ([согласная, знак] для слогов), keys (слова), intro, extra, tcons/tmarks (таблица)
function vowelLesson(id, prev, o) {
  const P = o.pairs, K = o.keys;
  const multi = K.find(k => W[k][3].length >= 2);
  const drills = [
    ...o.newMarks.flatMap(m => [markQ(m, o.known), markNameQ(m, o.known)]), ...[findMarkQ(o.newMarks[0], o.known)].filter(Boolean),
    ...P.slice(0, 3).map(([c, m]) => sylQ(c, m, o.cons, o.known)), bySylQ(...P[3], o.cons, o.known), typedSylQ(...P[4]), matchSylQ(P.slice(0, 4)), readSylQ(P),
    meaningQ(K[0], K), meaningQ(K[1], K), findWordQ(K[2], K), ...(multi ? [orderWordQ(multi)] : []), listenWordQ(K[3], K), readAloudQ(K),
    ...(o.extra ?? []),
  ];
  return {
    id, title: o.title, minutes: o.minutes ?? 7, stage: 'Огласовки', needs: [prev], intro: o.intro, goal: o.goal, body: o.body, task: o.task, decay: 1.3,
    table: sylTable(o.tcons ?? o.cons.slice(0, 4), o.tmarks ?? o.newMarks), words: wordsOf(K),
    cards: [...o.newMarks.map(m => [showMark(m), `${MARK[m]}: звук «${markSound(m)}»`]), ...wordCards(K.slice(0, 4)), ...(o.cards ?? [])], drills,
  };
}

