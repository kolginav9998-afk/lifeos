// ---------- поиск по словам, с формами слов ----------
// Слова-связки в запросе не мешают: «как обновить приложение» ищется по словам «обновить» и «приложение».
const STOP = new Set(['как', 'что', 'где', 'когда', 'мне', 'мой', 'моя', 'мои', 'мое', 'можно', 'нужно', 'надо', 'ли', 'не', 'и', 'в', 'во', 'на', 'с', 'со', 'к', 'ко', 'по', 'из', 'за', 'у', 'о', 'об', 'от', 'до', 'для',
  'это', 'то', 'а', 'но', 'или', 'же', 'бы', 'я', 'мы', 'ты', 'вы', 'он', 'она', 'они', 'так', 'при', 'про', 'еще', 'есть', 'если', 'без', 'над', 'под', 'чтобы']);

// Окончания, которые отбрасываем у слова (длинные первыми). Основа остаётся не короче трёх букв.
// У глаголов так «забыл», «забыла», «забыли», «забыть» дают одну основу «забы».
const ENDINGS = ['иями', 'ями', 'ами', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'ией', 'иям', 'иях', 'ием', 'ешь', 'ишь', 'ете', 'ите', 'ают', 'яют', 'ует', 'уют', 'ает', 'яет',
  'ой', 'ей', 'ый', 'ий', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие', 'ых', 'их', 'ом', 'ем', 'ам', 'ям', 'ах', 'ях', 'ов', 'ев', 'ию', 'ью', 'ия', 'ье', 'ую', 'юю', 'ут', 'ют', 'ат', 'ят', 'ет', 'ит', 'ла', 'ли', 'ло', 'ть', 'ся', 'сь', 'ии',
  'а', 'я', 'о', 'е', 'и', 'ы', 'у', 'ю', 'ь', 'й', 'л'].sort((a, b) => b.length - a.length);

export function stem(word) {
  const w = normalize(word);
  if (w.length <= 3) return w;
  for (const end of ENDINGS) if (w.length - end.length >= 3 && w.endsWith(end)) return w.slice(0, -end.length);
  return w;
}
const wordsOf = text => normalize(text).split(/[^\p{L}\p{N}]+/u).filter(Boolean);
// Слова совпадают, если у них одна основа или одна — начало другой (не короче четырёх букв): «обновить» ~ «обновление».
const same = (a, b) => {
  if (a === b) return true;
  const [s, l] = a.length <= b.length ? [a, b] : [b, a];
  return s.length >= 4 && l.startsWith(s);
};

// Вес совпадения по полям: заголовок важнее слов поиска, они важнее вступления, оно важнее шагов.
const W_TITLE = 8, W_KEYS = 6, W_LEAD = 3, W_BODY = 1;
let index = null;
function buildIndex() {
  const stems = texts => texts.flatMap(t => wordsOf(t).map(stem));
  return HELP_ARTICLES.map(a => ({
    article: a,
    title: normalize(a.title), keys: a.keywords.map(normalize),
    fields: [
      [W_TITLE, stems([a.title])], [W_KEYS, stems(a.keywords)], [W_LEAD, stems([a.summary, a.intro ?? ''])],
      [W_BODY, stems([a.stepsTitle ?? '', ...a.steps, ...(a.parts ?? []).flatMap(p => [p.title, ...p.steps]), ...(a.limits ?? [])])],
    ],
  }));
}

// Найти статьи по запросу: каждое слово запроса должно встретиться в статье. Лучшие первыми.
export function searchHelp(query, limit = 20) {
  const qs = wordsOf(query).filter(t => !STOP.has(t)).map(stem);
  if (!qs.length) return [];                                            // пусто или одни связки («как», «что»)
  index ??= buildIndex();
  const phrase = normalize(query).replace(/\s+/g, ' ').trim();
  const out = [];
  index.forEach((ix, order) => {
    let score = 0;
    for (const q of qs) {
      const w = Math.max(0, ...ix.fields.map(([weight, stems]) => (stems.some(s => same(q, s)) ? weight : 0)));
      if (!w) return;
      score += w;
    }
    if (phrase.length >= 4 && (ix.title.includes(phrase) || ix.keys.some(k => k.includes(phrase)))) score += 4;     // фраза целиком
    out.push({ article: ix.article, score, order });
  });
  out.sort((a, b) => b.score - a.score || a.order - b.order);
  return out.slice(0, limit).map(x => x.article);
}
